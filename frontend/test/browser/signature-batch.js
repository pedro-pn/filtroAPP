async (page) => {
  const assert = (value, message) => { if (!value) throw new Error(message); };
  const base = page.url().split('/test/')[0] + '/test/browser/signature-batch.html';
  await page.evaluate(() => sessionStorage.removeItem('signature-batch-fixture'));
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto(base);
  await page.getByRole('button', { name: 'Novo documento', exact: true }).first().click();
  await page.locator('#signature-pdf').setInputFiles([
    { name: 'primeiro.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-first') },
    { name: 'segundo.pdf', mimeType: 'application/pdf', buffer: Buffer.from('%PDF-second') }
  ]);
  assert(await page.getByRole('list', { name: 'Arquivos selecionados' }).locator('li').count() === 2, 'A seleção deve manter os dois arquivos');
  await page.getByRole('button', { name: 'Enviar e avançar', exact: true }).click();
  await page.getByText(/segundo.pdf:.*Tente novamente/).waitFor();
  await page.getByRole('button', { name: 'Enviar e avançar', exact: true }).click();
  await page.getByRole('heading', { name: 'Preparar lote de assinaturas' }).waitFor();
  assert((await page.evaluate(() => window.signatureBatchFixture.uploads)).join(',') === 'primeiro.pdf,segundo.pdf', 'O retry não pode duplicar o primeiro upload');
  assert(await page.getByRole('region', { name: 'Documentos do lote', exact: true }).count() === 1, 'Deve haver uma única rolagem para todo o lote');
  assert(await page.locator('.signature-batch-document').count() === 2, 'Os PDFs devem aparecer em sequência');
  await page.getByRole('textbox', { name: 'Nome', exact: true }).fill('Ana Souza');
  await page.getByRole('textbox', { name: 'E-mail', exact: true }).fill('ana@example.com');
  await page.getByRole('button', { name: 'Adicionar', exact: true }).click();
  const first = page.locator('[data-document-id="doc-1"] .signature-pdf-canvas.is-ready').first();
  await first.waitFor();
  await first.click({ position: { x: 180, y: 220 } });
  await page.locator('[data-document-id="doc-1"] .signature-field').waitFor();
  await page.getByRole('textbox', { name: 'Nome', exact: true }).fill('Bia Souza');
  await page.getByRole('textbox', { name: 'E-mail', exact: true }).fill('bia@example.com');
  await page.getByRole('button', { name: 'Adicionar', exact: true }).click();
  await page.getByRole('button', { name: 'Remover Bia Souza', exact: true }).waitFor();
  assert(await page.locator('[data-document-id="doc-1"] .signature-field').count() === 1, 'Adicionar assinante deve preservar posições anteriores');
  const secondDocument = page.locator('[data-document-id="doc-2"]');
  const navigation = page.getByRole('navigation', { name: 'Navegação entre documentos' });
  const documentSelect = navigation.getByRole('combobox', { name: 'Ir para documento' });
  assert(await navigation.evaluate(element => !element.closest('.signature-pdf-scroll')), 'A navegação deve ficar fora da visualização');
  assert(await page.locator('.signature-batch-document__header').evaluateAll(headers => headers.every(header => getComputedStyle(header).position === 'static')), 'Os separadores não podem flutuar sobre os PDFs');
  assert(await navigation.getByRole('button', { name: 'Documento anterior' }).isDisabled(), 'Primeiro documento não tem anterior');
  await navigation.getByRole('button', { name: 'Próximo documento' }).click();
  await page.waitForFunction(() => document.querySelector('[aria-label="Ir para documento"]').value === 'doc-2');
  assert(await navigation.getByRole('button', { name: 'Próximo documento' }).isDisabled(), 'Último documento não tem próximo');
  await documentSelect.selectOption('doc-1');
  await navigation.getByRole('button', { name: 'Próximo documento' }).click();
  const second = secondDocument.locator('.signature-pdf-canvas.is-ready').first();
  await second.waitFor();
  await second.click({ position: { x: 180, y: 220 } });
  await second.locator('.signature-signer-picker-option').filter({ hasText: 'Bia Souza' }).click();
  await page.getByRole('button', { name: 'Salvar campos', exact: true }).click();
  await page.getByText('Configuração salva.', { exact: true }).waitFor();
  await page.reload();
  await page.getByRole('heading', { name: 'Preparar lote de assinaturas' }).waitFor();
  const stored = await page.evaluate(() => window.signatureBatchFixture.batch.documents.map(document => ({ id: document.id, signers: document.signers.map(signer => signer.name), pages: document.fields.map(field => field.pageNumber) })));
  assert(JSON.stringify(stored) === JSON.stringify([{ id: 'doc-1', signers: ['Ana Souza'], pages: [1] }, { id: 'doc-2', signers: ['Bia Souza'], pages: [1] }]), 'Cada documento deve manter suas próprias posições e assinantes após reload');
  await page.screenshot({ path: 'output/playwright/assinaturas-lote-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), 'A tela mobile não deve ter overflow horizontal');
  await navigation.getByRole('button', { name: 'Próximo documento' }).click();
  await navigation.getByRole('button', { name: 'Documento anterior' }).click();
  await page.getByRole('region', { name: 'Documentos do lote', exact: true }).evaluate(element => { element.scrollTop = element.scrollHeight; });
  await page.waitForFunction(() => document.querySelector('[aria-label="Ir para documento"]').value === 'doc-2');
  await navigation.getByRole('button', { name: 'Documento anterior' }).click();
  await page.screenshot({ path: 'output/playwright/assinaturas-lote-mobile.png', fullPage: true });
  await page.getByRole('button', { name: 'Publicar lote', exact: true }).click();
  await page.getByRole('button', { name: 'Publicar', exact: true }).click();
  await page.getByRole('heading', { name: 'Acompanhamento do lote', exact: true }).waitFor();
  const publication = await page.evaluate(() => window.signatureBatchFixture.publication);
  assert(JSON.stringify(publication) === JSON.stringify([{ document: 'doc-1', signers: ['Ana Souza'] }, { document: 'doc-2', signers: ['Bia Souza'] }]), 'A publicação deve restringir convites aos documentos atribuídos');
  await page.getByRole('button', { name: 'Voltar', exact: true }).click();
  await page.getByRole('region', { name: 'Biblioteca de documentos', exact: true }).waitFor();
  assert(await page.locator('[data-signature-document]').count() === 1, 'A biblioteca deve exibir um único card para o lote');
  assert(await page.locator('.assinaturas-batch-document').count() === 2, 'O card deve listar os dois documentos');
  return { passed: true, checks: ['seleção múltipla', 'retry sem duplicação', 'rolagem contínua', 'navegação anterior/próximo e seleção direta', 'cabeçalho externo sem sobreposição', 'campos preservados ao adicionar assinante', 'atribuição por documento', 'retomada após reload', 'layout mobile', 'publicação do lote'] };
}
