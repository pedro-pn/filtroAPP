-- Transactional cache invalidation. Each backend updates only its own row,
-- avoiding a global write lock. Markers commit/roll back with application data.
-- Only named Prisma application tables are changed; historical/backup copies
-- and operational polling/session records are deliberately outside this list.
CREATE TABLE "public"."PerformanceReadRevision" (
  "id" UUID NOT NULL DEFAULT gen_random_uuid(),
  "writerPid" INTEGER NOT NULL,
  "revision" BIGINT NOT NULL DEFAULT 0,
  "updatedAt" TIMESTAMP(3) NOT NULL DEFAULT CURRENT_TIMESTAMP,
  CONSTRAINT "PerformanceReadRevision_pkey" PRIMARY KEY ("id")
);
CREATE UNIQUE INDEX "PerformanceReadRevision_writerPid_key" ON "public"."PerformanceReadRevision"("writerPid");
INSERT INTO "public"."PerformanceReadRevision" ("writerPid") VALUES (0);

CREATE FUNCTION "public"."bump_performance_read_revision"() RETURNS trigger
LANGUAGE plpgsql SET search_path = pg_catalog AS $$
BEGIN
  INSERT INTO "public"."PerformanceReadRevision" ("writerPid", "revision", "updatedAt")
  VALUES (pg_backend_pid(), 1, clock_timestamp())
  ON CONFLICT ("writerPid") DO UPDATE
  SET "revision" = "PerformanceReadRevision"."revision" + 1, "updatedAt" = clock_timestamp();
  RETURN NULL;
END;
$$;

